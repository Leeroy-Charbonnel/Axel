import { Router } from "express"
import sharp, { type Sharp } from "sharp"
import { IMAGE_FORMATS, IMAGE_WIDTHS, storedImage, type ImageFormat } from "../src/lib/media"
import { objectExists, readObject, sendObject, writeObject } from "./storage"

//IMAGE DERIVATIVES. /media/{format}/{width}/{storedFilename} answers the
//upload resized to that width (never enlarged), encoded once and kept in the
//bucket under .cache/{format}/{width}/{storedFilename}.{format}. The /media
//route never serves .cache raw. The cache holds derived bytes only: deleting
//it is always safe.
const CACHE_PREFIX = ".cache"
const YEAR_SECONDS = 60 * 60 * 24 * 365

//the cached copies of one stored image, every format and width
export function derivativeKeys(stored: string): string[] {
  return IMAGE_FORMATS.flatMap((f) => IMAGE_WIDTHS.map((w) => cacheKey(stored, f, w)))
}

function cacheKey(stored: string, format: ImageFormat, width: number): string {
  return `${CACHE_PREFIX}/${format}/${width}/${stored}.${format}`
}

//an encode holds a decoded image in memory and a core busy
const MAX_ENCODES = 2

const ENCODE: Record<ImageFormat, (s: Sharp) => Sharp> = {
  webp: (s) => s.webp({ quality: 80, effort: 4 }),
  jpeg: (s) => s.jpeg({ quality: 82, mozjpeg: true }),
}

//two requests for the same derivative share one encode
const inFlight = new Map<string, Promise<void>>()
//stored files never change, so a source sharp could not read stays unreadable
//until the process restarts
const failed = new Set<string>()

let running = 0
const waiting: Array<() => void> = []

async function limited<T>(job: () => Promise<T>): Promise<T> {
  while (running >= MAX_ENCODES) await new Promise<void>((resolve) => waiting.push(resolve))
  running++
  try {
    return await job()
  } finally {
    running--
    waiting.shift()?.()
  }
}

//sharp failed on the source bytes, as opposed to the storage failing on ours
class DecodeError extends Error {}

async function encode(stored: string, target: string, format: ImageFormat, width: number): Promise<void> {
  const source = await readObject(stored)
  let bytes: Buffer
  try {
    bytes = await limited(() => ENCODE[format](sharp(source).autoOrient().resize({ width, withoutEnlargement: true })).toBuffer())
  } catch (e) {
    throw new DecodeError(e instanceof Error ? e.message : String(e))
  }
  await writeObject(target, bytes)
}

export const imagesRouter = Router()

imagesRouter.get("/media/:format/:width/*path", async (req, res, next) => {
  const format = req.params.format as ImageFormat
  const width = Number(req.params.width)
  const stored = (req.params.path as string[]).join("/")
  //a stored file has three segments too (shared/images/x.jpg): not a format
  //and a width, it goes on to the /media route
  if (!IMAGE_FORMATS.includes(format) || !IMAGE_WIDTHS.includes(width)) {
    next()
    return
  }
  //the stored name is generated by uploads.ts, so anything else is refused
  //before the storage is touched: no "..", no other directory, no other type
  if (storedImage(`/media/${stored}`) !== stored) {
    res.status(404).end()
    return
  }
  const target = cacheKey(stored, format, width)
  if (failed.has(target)) {
    res.status(404).end()
    return
  }
  //the common case: encoded already
  if (await sendObject(req, res, target, YEAR_SECONDS)) return
  if (!(await objectExists(stored))) {
    res.status(404).end()
    return
  }
  let job = inFlight.get(target)
  if (!job) {
    job = encode(stored, target, format, width).finally(() => inFlight.delete(target))
    inFlight.set(target, job)
  }
  try {
    await job
  } catch (e) {
    if (!(e instanceof DecodeError)) throw e
    //bytes stored under an image name that sharp cannot read: a 404, one log line
    if (!failed.has(target)) {
      failed.add(target)
      console.error(`[images] ${stored} cannot be encoded to ${format} ${width}, answered 404 until restart: ${e.message}`)
    }
    res.status(404).end()
    return
  }
  if (!(await sendObject(req, res, target, YEAR_SECONDS))) {
    throw new Error(`[images] ${target} was encoded but is not in the bucket`)
  }
})
